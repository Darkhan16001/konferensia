function updateZoom(center = false) {

    const viewportWidth = stage.clientWidth;

    const viewportHeight = stage.clientHeight;

    if (!viewportWidth || !viewportHeight) {

        return;

    }

    const oldWidth = zoomFrame.offsetWidth;
    const oldHeight = zoomFrame.offsetHeight;

    let focusX = .5;
    let focusY = .5;


    // ҮЛКЕЙТІП ҚАРАП ТҰРҒАН ОРЫНДЫ САҚТАУ

    if (!center && oldWidth && oldHeight) {

        focusX = clamp(

            (
                stage.scrollLeft +
                viewportWidth / 2 -
                zoomFrame.offsetLeft
            ) / oldWidth,

            0,
            1

        );

        focusY = clamp(

            (
                stage.scrollTop +
                viewportHeight / 2 -
                zoomFrame.offsetTop
            ) / oldHeight,

            0,
            1

        );

    }


    // 100% — ҚАЛЫПТЫ ӨЛШЕМ

    const fitScale = Math.max(

        .001,

        Math.min(

            (viewportWidth - 12) / W,

            (viewportHeight - 12) / H

        )

    );

    zoom = clamp(
        zoom,
        MIN_ZOOM,
        MAX_ZOOM
    );

    const scale = fitScale * zoom / 100;

    const newWidth = Math.ceil(W * scale);

    const newHeight = Math.ceil(H * scale);


    // БҮКІЛ ПРЕЗЕНТАЦИЯ БІРГЕ МАСШТАБТАЛАДЫ

    slide.style.transform =
        `scale(${scale})`;

    zoomFrame.style.width =
        newWidth + "px";

    zoomFrame.style.height =
        newHeight + "px";


    // ҮЛКЕЙТІЛГЕН СЛАЙДҚА ОРЫН АШУ

    workspace.style.width = Math.max(
        viewportWidth,
        newWidth + 12
    ) + "px";

    workspace.style.height = Math.max(
        viewportHeight,
        newHeight + 12
    ) + "px";

    stage.classList.toggle(

        "zoomed",

        workspace.offsetWidth > viewportWidth ||
        workspace.offsetHeight > viewportHeight

    );


    // ЭКРАННЫҢ ОРТАЛЫҒЫН САҚТАУ

    stage.scrollLeft =
        zoomFrame.offsetLeft +
        focusX * newWidth -
        viewportWidth / 2;

    stage.scrollTop =
        zoomFrame.offsetTop +
        focusY * newHeight -
        viewportHeight / 2;


    // БАСҚАРУ БАТЫРМАЛАРЫ

    $("zoomValue").textContent = zoom + "%";

    $("zoomSlider").value = zoom;

    $("zoomOut").disabled = zoom <= MIN_ZOOM;

    $("zoomIn").disabled = zoom >= MAX_ZOOM;

    $("zoomMax").disabled = zoom >= MAX_ZOOM;

}

function setZoom(value, center = false) {

    zoom = clamp(
        Number(value),
        MIN_ZOOM,
        MAX_ZOOM
    );

    updateZoom(center);

}

