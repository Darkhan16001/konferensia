// ҚАЗАҚША ӘРІПТЕРДІ ДҰРЫС БӨЛУ

function prepareWriting() {

    stopWriting();

    writingChars = [];

    const blocks = slide.querySelectorAll(

        "h1, .lead, .paragraph, .callout, .conference-info, .slogan"

    );

    blocks.forEach(block => {

        const walker = document.createTreeWalker(
            block,
            NodeFilter.SHOW_TEXT
        );

        const nodes = [];

        let node;

        while ((node = walker.nextNode())) {

            if (node.nodeValue.trim()) {

                nodes.push(node);

            }

        }

        nodes.forEach(textNode => {

            const fragment =
                document.createDocumentFragment();

            const parts = textNode.nodeValue
                .normalize("NFC")
                .split(/(\s+)/u);

            parts.forEach(part => {

                if (!part) return;

                // Бос орындар сақталады

                if (/^\s+$/u.test(part)) {

                    fragment.appendChild(
                        document.createTextNode(part)
                    );

                    return;

                }

                // Сөз ортадан бөлінбейді

                const word =
                    document.createElement("span");

                word.className = "typed-word";

                const chars = Array.from(part);

                chars.forEach(character => {

                    const span =
                        document.createElement("span");

                    span.className = "typed-char";

                    span.textContent = character;

                    word.appendChild(span);

                    writingChars.push(span);

                });

                fragment.appendChild(word);

            });

            textNode.replaceWith(fragment);

        });

    });

}


// АДАМ ЖАЗЫП ЖАТҚАНДАЙ АНИМАЦИЯ

function startWriting() {

    stopWriting();

    if (!writingEnabled || !writingChars.length) {

        showAllText();

        return;

    }

    writingChars.forEach(char => {

        char.classList.add("waiting");

        char.classList.remove("cursor");

    });

    $("showText").disabled = false;

    const count = writingChars.length;

    const duration = Math.min(
        7500,
        Math.max(1800, count * 13)
    );

    let totalWeight = 0;

    const schedule = writingChars.map(char => {

        totalWeight += /[.,!?;:]/u.test(
            char.textContent
        )
            ? 3
            : 1 + Math.random() * .6;

        return totalWeight;

    });

    let started = null;
    let revealed = 0;
    let previous = null;

    function animate(timestamp) {

        if (started === null) {

            started = timestamp;

        }

        const progress = Math.min(
            1,
            (timestamp - started) / duration
        );

        const limit = progress * totalWeight;

        if (previous) {

            previous.classList.remove("cursor");

        }

        while (
            revealed < count &&
            schedule[revealed] <= limit
        ) {

            writingChars[revealed]
                .classList.remove("waiting");

            previous = writingChars[revealed];

            revealed++;

        }

        if (previous && progress < 1) {

            previous.classList.add("cursor");

        }

        if (progress < 1) {

            writingFrame =
                requestAnimationFrame(animate);

        } else {

            showAllText();

        }

    }

    writingFrame =
        requestAnimationFrame(animate);

}


