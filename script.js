document.addEventListener("keydown", event => {

    if (document.querySelector("dialog[open]")) {

        return;

    }

    if (
        event.ctrlKey ||
        event.metaKey ||
        event.altKey
    ) {

        return;

    }

    if (["INPUT", "TEXTAREA", "SELECT"]
        .includes(event.target.tagName)) {

        return;

    }


    // SHIFT + БАҒЫТТАУ

    if (event.shiftKey) {

        const directions = {

            ArrowLeft: [-100, 0],

            ArrowRight: [100, 0],

            ArrowUp: [0, -100],

            ArrowDown: [0, 100]

        };

        if (directions[event.key]) {

            event.preventDefault();

            stage.scrollBy(
                ...directions[event.key]
            );

            return;

        }

    }


    // СЛАЙД АУЫСТЫРУ

    if (["ArrowRight", "ArrowDown", "PageDown"]
        .includes(event.key)) {

        event.preventDefault();

        nextSlide();

    }

    if (["ArrowLeft", "ArrowUp", "PageUp"]
        .includes(event.key)) {

        event.preventDefault();

        prevSlide();

    }


    // МӘТІНДІ БІРДЕН КӨРСЕТУ

    if (
        event.key === "Enter" &&
        !event.target.closest("button, a")
    ) {

        event.preventDefault();

        showAllText();

    }


    // МӘТІНДІ ҚАЙТА ЖАЗУ

    if (event.key.toLowerCase() === "r") {

        writingEnabled = true;

        updateWritingButton();

        startWriting();

    }


    // МАСШТАБТАУ

    if (event.key === "+" || event.key === "=") {

        event.preventDefault();

        setZoom(zoom + 5);

    }

    if (event.key === "-") {

        event.preventDefault();

        setZoom(zoom - 5);

    }

    if (event.key === "0") {

        setZoom(100, true);

    }

    if (event.key.toLowerCase() === "m") {

        setZoom(300, true);

    }


    // ТОЛЫҚ ЭКРАН

    if (event.key.toLowerCase() === "f") {

        toggleFullscreen();

    }


    // БАЯНДАМА

    if (event.key.toLowerCase() === "n") {

        showAllText();

        $("notesDialog").showModal();

    }


    // ТАЙМЕР

    if (
        event.code === "Space" &&
        !event.target.closest("button, a")
    ) {

        event.preventDefault();

        toggleTimer();

    }


    // БІРІНШІ ЖӘНЕ СОҢҒЫ СЛАЙД

    if (event.key === "Home") {

        event.preventDefault();

        current = 0;

        render();

    }

    if (event.key === "End") {

        event.preventDefault();

        current = slides.length - 1;

        render();

    }

    if (event.key === "Escape") {

        $("menu").hidden = true;

    }

});


