function fitContent() {

    const content =
        slide.querySelector(".content");

    const copy =
        slide.querySelector(".copy");

    if (!content || !copy) return;

    const style = getComputedStyle(content);

    const availableHeight =
        content.clientHeight -
        parseFloat(style.paddingTop) -
        parseFloat(style.paddingBottom) - 5;

    let size = 30;

    content.style.setProperty(
        "--text-size",
        size + "px"
    );

    while (
        copy.offsetHeight > availableHeight &&
        size > 12
    ) {

        size -= .5;

        content.style.setProperty(
            "--text-size",
            size + "px"
        );

    }

}


